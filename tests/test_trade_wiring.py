"""Test the /trade wiring patches and verify they produce a working
integration of upstream hermes-agent 0.19.0 + TradeDesk.

This test:
1. Builds a fixture by copying upstream hermes-agent 0.19.0 files.
2. Copies the public package TradeDesk + trade_menu + positions_menu
   files into the fixture.
3. Applies the public package's hermes_overlay/patches/ patches to the
   upstream files.
4. Imports the patched adapter and verifies:
   - /trade command dispatch reaches trade_menu.handle_trade_command
   - tm: callback dispatch reaches trade_menu.handle_trade_callback
   - text dispatch reaches trade_menu.handle_trade_text
   - ordinary text falls through to the LLM path (no exception)

No network calls. No live trades.
"""

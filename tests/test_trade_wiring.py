import shutil
import subprocess
import sys
import tempfile
import urllib.request
import zipfile
import io
from pathlib import Path
from unittest.mock import MagicMock, AsyncMock

# === Constants ===
WHEEL_URL = "https://files.pythonhosted.org/packages/e5/30/c85be8290e9565dc3c7a9720e93f3e59e09b1b163487be4946c3aa848f80/hermes_agent-0.19.0-py3-none-any.whl"
PUB = Path(__file__).parent.parent  # hermes-tradedesk-public

# === Build the fixture ===
print("=== Building test fixture ===")
TMPDIR = Path(tempfile.mkdtemp(prefix="trade_wiring_test_"))
print(f"  fixture: {TMPDIR}")

# Layout
(TMPDIR / "hermes_cli").mkdir(parents=True)
(TMPDIR / "plugins" / "platforms" / "telegram" / "trade_menu").mkdir(parents=True)
(TMPDIR / "plugins" / "platforms" / "telegram" / "positions_menu").mkdir(parents=True)

# Download upstream.
wheel = "/tmp/hermes_agent-0.19.0.whl"
if not os.path.exists(wheel):
    urllib.request.urlretrieve(WHEEL_URL, wheel)
with zipfile.ZipFile(wheel) as zf:
    # The upstream wheel only has explicit __init__.py at:
    #   plugins/__init__.py
    #   plugins/platforms/telegram/__init__.py
    # `plugins/platforms/__init__.py` is an implicit namespace package and
    # is NOT in the wheel. We just create the directory.
    for member in [
        "hermes_cli/commands.py",
        "plugins/platforms/telegram/adapter.py",
        "plugins/platforms/telegram/telegram_ids.py",
        "plugins/platforms/telegram/telegram_network.py",
        "plugins/__init__.py",
        "plugins/platforms/telegram/__init__.py",
    ]:
        with zf.open(member) as src:
            target = TMPDIR / member
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(src.read())
        print(f"  copied upstream: {member}")
    # Create the implicit namespace package directory.
    (TMPDIR / "plugins" / "platforms").mkdir(parents=True, exist_ok=True)
    print("  created implicit namespace: plugins/platforms/")

# Copy public package files.
# Copy tradedesk (whole dir).
shutil.copytree(PUB / "tradedesk", TMPDIR / "tradedesk")

# Copy telegram overlay files individually (the destination dirs already
# exist from the upstream extraction).
for f in ("wizard.py",):
    shutil.copy(PUB / "hermes_overlay" / "telegram" / "trade_menu" / f,
                TMPDIR / "plugins" / "platforms" / "telegram" / "trade_menu" / f)
# trade_menu/__init__.py is generated by the install (or by the upstream).
# Use a minimal stub for testing.
(TMPDIR / "plugins" / "platforms" / "telegram" / "trade_menu" / "__init__.py").write_text(
    "from .wizard import handle_trade_command, handle_trade_text, handle_trade_callback\n"
    "__all__ = ['handle_trade_command', 'handle_trade_text', 'handle_trade_callback']\n"
)

# positions_menu: only the handlers are needed; the upstream may not have this
# package. Create a stub that mirrors our public package's structure.

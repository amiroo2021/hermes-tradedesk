# Mock the trade_menu module so the dispatches can be intercepted.
import types


def setup_adapter():
    """Build a minimal adapter instance and mock its helpers."""
    from plugins.platforms.telegram import adapter as adapter_mod
    TelegramAdapter = adapter_mod.TelegramAdapter
    adapter = TelegramAdapter.__new__(TelegramAdapter)
    adapter._trade_menu_state = {}
    adapter._positions_menu_state = {}
    return adapter, TelegramAdapter


# 2a. /trade command dispatch.
print("  2a. /trade command dispatch → trade_menu.handle_trade_command")
try:
    adapter, TelegramAdapter = setup_adapter()
    calls = []
    fake_tm = types.ModuleType("plugins.platforms.telegram.trade_menu")
    async def fake_command(adapter, msg):
        calls.append(("command", msg.text))
        return True
    fake_tm.handle_trade_command = fake_command
    fake_tm.handle_trade_text = lambda a, m: asyncio.sleep(0)
    fake_tm.handle_trade_callback = lambda a, q, d: asyncio.sleep(0)
    sys.modules["plugins.platforms.telegram.trade_menu"] = fake_tm
    fake_pm = types.ModuleType("plugins.platforms.telegram.positions_menu")
    fake_pm.handle_positions_command = lambda a, m: asyncio.sleep(0)
    fake_pm.handle_positions_text = lambda a, m: asyncio.sleep(0)
    fake_pm.handle_positions_callback = lambda a, q, d: asyncio.sleep(0)
    sys.modules["plugins.platforms.telegram.positions_menu"] = fake_pm
    # Mock helpers.
    adapter._is_user_authorized_from_message = lambda msg: True
    adapter._should_process_message = lambda msg, is_command=False: True
    adapter._should_observe_unmentioned_group_message = lambda msg: False
    adapter._observe_unmentioned_group_message = lambda *a, **k: None
    adapter._effective_update_message = lambda u: u.effective_message
    adapter._ensure_forum_commands = AsyncMock()
    adapter.handle_message = AsyncMock()
    adapter._build_message_event = lambda *a, **k: MagicMock()
    adapter._clean_bot_trigger_text = lambda t: t
    adapter._cache_replied_media = AsyncMock()
    adapter._apply_telegram_group_observe_attribution = lambda e: e
    adapter._enqueue_text_event = lambda e: None
    # Build fake message.
    msg = MagicMock(text="/trade", from_user=MagicMock(id=1), chat=MagicMock(id=1), message_thread_id=None)
    update = MagicMock(update_id=1, effective_message=msg, message=msg)
    import asyncio
    asyncio.run(TelegramAdapter._handle_command(adapter, update, None))
    if any(c[0] == "command" for c in calls):
        print("    [PASS] trade_menu.handle_trade_command was called")
    else:
        failures.append("2a. command dispatch did not call trade_menu")
        print("    [FAIL] command dispatch did not call trade_menu")
except Exception as e:
    failures.append(f"2a. exception: {e}")
    print(f"    [FAIL] {type(e).__name__}: {e}")

